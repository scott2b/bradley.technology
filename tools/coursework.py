"""Generate data/coursework.toml from the transcript record.

Source: ~/vault/archive/courses-and-academic-completions.md
Keyed by credential slug so templates/credential.html can look up its own courses.

Deliberately excluded:
  - Wheaton and Notre Dame. The theology work is off the site; see
    EXPERIENCE_TIMELINE.md in the vault project (~/vault/projects/BradleyTechnology)
    for why, and for the thematic question it leaves open.
  - College of DuPage. One audited photography course on the record; the Data
    Structures in C++ course has no date yet.
  - Audited courses (grade AU), which carried no credit.

Grades are not carried through. A portfolio lists what was studied, not marks.

A handful of courses have a surviving paper. Those are mapped by hand in ARTIFACTS
below — the transcript does not record them — and published from static/artifacts.
The two group-authored papers in the archive (SE 430 Smart Kitchen, CSC 587
Tie-O-Matic) are not published: they carry other students' names. Those courses link
to their project pages instead, mapped in PROJECTS.
"""
import pathlib, re, collections

SRC = pathlib.Path.home() / "vault/archive/courses-and-academic-completions.md"
OUT = pathlib.Path(__file__).resolve().parent.parent / "data" / "coursework.toml"
TERM = {"sp": "Spring", "su": "Summer", "fa": "Fall", "au": "Autumn", "wi": "Winter"}
SEQ = {"Winter": 0, "Spring": 1, "Summer": 2, "Fall": 3, "Autumn": 3}
OWNER = {"Purdue": "purdue-bsee", "DePaul": "depaul-mscs",
         "UIC": "uic-bioinformatics", "Capella": "capella-coursework"}

ARTIFACTS = {
    ("capella-coursework", "TS 7020"): (
        "Portfolio design plan", "portfolio-design-plan.pdf"),
    ("capella-coursework", "TS 5130"): (
        "Applying software engineering practice to the deployment of Nortel Preside",
        "nortel-preside-deployment-analysis.pdf"),
    ("capella-coursework", "TS 5501"): (
        "Design of the general contractor database",
        "general-contractor-database-design.pdf"),
    ("capella-coursework", "TS 5516"): (
        "Implementation of a client-server network: engineering and maintenance guide",
        "client-server-network-implementation.pdf"),
    ("depaul-mscs", "SE 450"): (
        "Traffic simulator design", "traffic-simulator-design.pdf"),
    ("depaul-mscs", "CSC 541"): (
        "Parameter persistence in Gene Designer, Illinois Bio-Grid Protein Desktop",
        "gene-designer-parameter-persistence.pdf"),
}

PROJECTS = {
    ("depaul-mscs", "SE 430"): ("Smart Kitchen Central System", "@/projects/smart-kitchen.md"),
    ("depaul-mscs", "CSC 587"): ("Tie-O-Matic", "@/projects/tie-o-matic.md"),
}

# The transcript abbreviates the same word more than one way; the record stays
# verbatim and the site shows one spelling.
ABBREV = {"anal": "anly"}


def house(title):
    return re.sub(r"\b\w+\b", lambda w: ABBREV.get(w.group(0), w.group(0)), title)


rows = collections.defaultdict(list)
for line in SRC.read_text().splitlines():
    if not line.startswith("|") or "---" in line or "school" in line:
        continue
    p = [c.strip() for c in line.strip("|").split("|")]
    if len(p) < 6 or p[1] not in OWNER:
        continue
    date, school, grade, credits, code, title = p[:6]
    if grade.upper() == "AU" or not credits:
        continue                        # audited, no credit earned
    m = re.match(r"(sp|su|fa|au|wi)\s*(\d{4})", date)
    if not m:
        continue                        # completions table, not a course
    rows[OWNER[school]].append((int(m.group(2)), TERM[m.group(1)], code, house(title)))

def q(s):
    return s.replace(chr(34), chr(39))


out = ["# Generated by tools/coursework.py from the transcript record.",
       "# Do not edit by hand.", ""]
seen = set()
for slug in sorted(rows):
    items = sorted(rows[slug], key=lambda r: (r[0], SEQ[r[1]], r[2]))
    papers = sum(1 for _, _, c, _ in items if (slug, c) in ARTIFACTS)
    projects = sum(1 for _, _, c, _ in items if (slug, c) in PROJECTS)
    out += [f"[{slug}]", f"count = {len(items)}", f"papers = {papers}",
            f"projects = {projects}", "courses = ["]
    for y, s, c, t in items:
        row = f'  {{ term = "{s} {y}", code = "{c}", title = "{q(t)}"'
        if (slug, c) in ARTIFACTS:
            title, filename = ARTIFACTS[(slug, c)]
            seen.add((slug, c))
            row += f', paper = "{q(title)}", paper_file = "{filename}"'
        if (slug, c) in PROJECTS:
            title, path = PROJECTS[(slug, c)]
            seen.add((slug, c))
            row += f', project = "{q(title)}", project_path = "{path}"'
        out += [row + " },"]
    out += ["]", ""]
OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(out))

missing = (set(ARTIFACTS) | set(PROJECTS)) - seen
if missing:
    raise SystemExit(f"artifact mapped to a course not on the transcript: {missing}")
for slug in sorted(rows):
    papers = sum(1 for _, _, c, _ in rows[slug] if (slug, c) in ARTIFACTS)
    projects = sum(1 for _, _, c, _ in rows[slug] if (slug, c) in PROJECTS)
    print(f"  {slug:22s} {len(rows[slug]):>3} courses  {papers:>2} papers"
          f"  {projects:>2} projects")
